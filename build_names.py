"""Regenerate the numeric name indexes from an installed Pokopia 2.0.1 archive."""

import argparse
import struct
import zlib
from pathlib import Path


HERE = Path(__file__).resolve().parent
ROMFS = HERE.parents[1] / "room/updates/655360/romfs"
OUTPUT = HERE / "block_names_data.inc"


def read_table(romfs, entry, count, version, stride):
    index = (romfs / "LI_C0_R.IDX").read_bytes()
    if len(index) != 12298 * 32:
        raise ValueError("Expected the Pokopia 2.0.1 archive index")
    start, size, packed_size, compressed = struct.unpack_from("<4Q", index, entry * 32)
    with (romfs / "LD_C0_R.BIN").open("rb") as stream:
        stream.seek(start)
        data = stream.read(packed_size if compressed else size)
    if compressed:
        block_size, block_count, raw_size = struct.unpack_from("<3I", data)
        cursor = (12 + block_count * 4 + 127) & ~127
        unpacked = bytearray()
        for block in range(block_count):
            length = struct.unpack_from("<I", data, 12 + block * 4)[0]
            payload = data[cursor:cursor + length]
            expected = min(block_size, raw_size - len(unpacked))
            decoded = payload if length == expected else zlib.decompress(payload[4:])
            if len(decoded) != expected:
                raise ValueError(f"Incorrect decompressed block size in archive entry {entry}")
            unpacked.extend(decoded)
            cursor = (cursor + length + 127) & ~127
        data = unpacked
    if len(data) != size or size != 64 + count * stride or struct.unpack_from("<2I", data) != (count, version):
        raise ValueError(f"Unexpected format for archive entry {entry}")
    return memoryview(data)[64:]


def u16(data, offset):
    return struct.unpack_from("<H", data, offset)[0]


def terrain_names(items):
    names = [None] * 2048
    for item_id in range(4600):
        item = items[item_id * 68:(item_id + 1) * 68]
        if u16(item, 0x14) != 1:
            continue
        terrain, name = u16(item, 0x0c), u16(item, 0x22)
        if not (0 < terrain < len(names) and 0 < name <= 3000) or names[terrain]:
            raise ValueError(f"Invalid or duplicate terrain index for item {item_id}")
        names[terrain] = (name, item_id)
    return names


def variation_names(items, parts, variations):
    names = [None] * 4096
    for variation_id in range(1, len(names)):
        part = u16(variations, variation_id * 16 + 4)
        if not part:
            continue
        item = u16(parts, part * 80 + 6)
        if item:
            name = u16(items, item * 68 + 0x22)
            if name > 3000:
                raise ValueError(f"Invalid name index for part variation {variation_id}")
            names[variation_id] = (name, item)
    return names


def format_table(name, entries):
    yield f"static const BlockItem {name}[] = {{"
    for index, entry in enumerate(entries):
        if entry:
            name_id, item_id = entry
            yield f"    [{index}] = {{{name_id}, {item_id}}},"
    yield "};"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--romfs", type=Path, default=ROMFS)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    items = read_table(args.romfs, 983, 4600, 3, 68)
    parts = read_table(args.romfs, 40, 4096, 0, 80)
    variations = read_table(args.romfs, 41, 4096, 3, 16)
    data = "\n".join([
        "/* Generated by build_names.py. Each entry contains a name ID and an item ID. */",
        *format_table("terrain_names", terrain_names(items)),
        "",
        *format_table("part_names", variation_names(items, parts, variations)),
        "",
    ])
    if args.check:
        if OUTPUT.read_text(encoding="ascii") != data:
            parser.error(f"{OUTPUT.name} differs from the installed archive")
    else:
        OUTPUT.write_text(data, encoding="ascii", newline="\n")


if __name__ == "__main__":
    main()
